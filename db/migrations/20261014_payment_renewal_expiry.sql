-- Миграция (идемпотентная): целевой срок продления, зафиксированный за платежом.
--
-- Зачем: продление сначала меняет клиента в панели 3x-ui, потом пишет срок в БД.
-- Новый срок считается как max(now, expiry) + месяцы, поэтому повтор после сбоя
-- (или после перехвата захвата) добавил бы период ещё раз. Срок считается один раз,
-- записывается сюда до обращения к панели, и повтор использует уже сохранённое значение.
--
-- Применять на БД платформы (продакшн) вручную, до выката нового кода:
--   docker exec -i <postgres-container> psql -U <DB_USER> -d <DB_NAME> -v ON_ERROR_STOP=1 \
--     < db/migrations/20261014_payment_renewal_expiry.sql
-- Безопасна к повторному запуску. Только добавляет nullable-колонку, данные не меняет.

BEGIN;

ALTER TABLE payments
    ADD COLUMN IF NOT EXISTS renewal_expiry_time BIGINT;

COMMIT;
