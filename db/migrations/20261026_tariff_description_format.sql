-- Миграция (идемпотентная): приводит tariff.description к одной форме.
--
-- Описание выводится клиентам строкой под названием тарифа (бот/Mini App/web).
-- Раньше в нём были разные стили: «Тариф-100», «Пробный», «4 устройства без ограничений».
-- Теперь текст строится из реальных полей тарифа:
--   limit_ip = 0            → «Устройства и трафик без ограничений»
--   limit_ip = 1            → «1 устройство · трафик без ограничений»
--   limit_ip = N (N ≥ 2)    → «До N устройств · трафик без ограничений»
-- Строки с ограниченным трафиком (traffic_limit > 0) не трогаем: для них текст
-- «трафик без ограничений» был бы неверным. Таких сейчас нет.
--
-- Применять на БД вручную, до выката нового кода:
--   docker exec -i <postgres-container> psql -U <DB_USER> -d <DB_NAME> -v ON_ERROR_STOP=1 \
--     < db/migrations/20261026_tariff_description_format.sql
-- Безопасна к повторному запуску: значение целиком вычисляется из limit_ip.

BEGIN;

UPDATE tariff
SET description = CASE
    WHEN limit_ip = 0 THEN 'Устройства и трафик без ограничений'
    WHEN limit_ip = 1 THEN '1 устройство · трафик без ограничений'
    ELSE 'До ' || limit_ip || ' устройств · трафик без ограничений'
END
WHERE traffic_limit = 0;

COMMIT;
